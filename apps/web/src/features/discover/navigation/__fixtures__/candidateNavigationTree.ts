/**
 * Resolves a nodeKey to its normalized `NavigationNodeResponse`, via the REAL
 * `normalizeNavigationNode` parse path (`../normalize.ts`) — never a
 * fixture-only alternative. Mirrors what `GET .../navigation/resolve` would
 * return for one of this fixture's four modelled nodes: `'root'`,
 * `'d:central'`,
 * `'c:central:in-ka-bengaluru-avalahalli-in-ka-bengaluru-deepanjali-nagar'`,
 * or `'a:IN|KA|Bengaluru|Avalahalli'`. Returns `null` for any other key —
 * this fixture does not model the whole candidate tree (see module doc).
 */
export function resolveCandidateNode(nodeKey: string): NavigationNodeResponse | null {
  const wire = WIRE_BY_NODE_KEY.get(nodeKey);
  if (!wire) return null;
  return normalizeNavigationNode(wire);
}

