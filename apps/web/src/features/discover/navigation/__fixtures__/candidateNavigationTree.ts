/** Builds a leaf AREA node's NavigationChildSummary entry for a cluster's `children[]`. */
function areaChildSummary(
  nodeKey: string,
  areaKey: string,
  displayLabel: string,
  displayOrder: number,
): NavigationNodeWire['children'][number] {
  return {
    nodeKey,
    nodeType: 'AREA',
    displayLabel,
    displayOrder,
    areaKey,
    // No real centre/bounds is enumerated per-leaf in the candidate TOML for
    // AREA nodes (only for DIRECTION/CLUSTER) — omitted (undefined), which
    // `normalizeNavigationNode`/the strict `NavigationChildSummary` type both
    // treat identically to an explicit `null` (see types.ts's doc on that
    // interface).
  };
}

