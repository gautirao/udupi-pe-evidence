import { describe, it, expect } from 'vitest';
import {
  getHierarchyExtent,
  isSelectedNodeOutOfView,
  getCameraIntentForRecenter,
} from '../MapDiscovery.recenter';
import type { NavigationNodeResponse } from '@/features/discover/navigation/types';

describe('MapDiscovery recenter logic', () => {
  const MOCK_MAP_BBOX: [number, number, number, number] = [
    12.9, // south
    77.5, // west
    13.1, // north
    77.7, // east
  ];
  // usable area margins: lat 0.02, lonRight 0.05, lonLeft 0.02
  // usable map rect: [12.92, 77.52, 13.08, 77.65]

  function makeNode(
    centerLat: number,
    centerLon: number,
    children: Array<{ centreLat?: number; centreLon?: number }> = []
  ): NavigationNodeResponse {
    return {
      nodeKey: 'test',
      nodeType: 'AREA',
      displayLabel: 'Test Area',
      depth: 0,
      ancestry: [],
      children: children.map((c, i) => ({
        nodeKey: `c${i}`,
        nodeType: 'AREA',
        displayLabel: `Child ${i}`,
        depth: 1,
        ancestry: [],
        children: [],
        revisionId: 1,
        ...c,
      })) as any[],
      revisionId: 1,
      bounds: {
        centreLat: centerLat,
        centreLon: centerLon,
        minLat: centerLat - 0.01,
        maxLat: centerLat + 0.01,
        minLon: centerLon - 0.01,
        maxLon: centerLon + 0.01,
      },
      descendantAreaKeys: null,
      areaKey: null,
      regionKey: null,
      nextLevelType: 'NONE',
    };
  }

  it('1. selected centre inside + one/more direct children outside usable panel-aware frame => Recenter visible', () => {
    // node centre is inside usable rect (13.0, 77.6)
    // child is outside usable rect (e.g. 13.15, 77.6)
    const node = makeNode(13.0, 77.6, [{ centreLat: 13.15, centreLon: 77.6 }]);
    expect(isSelectedNodeOutOfView(node, MOCK_MAP_BBOX)).toBe(true);
  });

  it('2. all selected context/direct children adequately framed => Recenter hidden', () => {
    // node and children all inside usable rect: [12.92, 77.52, 13.08, 77.65]
    const node = makeNode(13.0, 77.6, [{ centreLat: 12.95, centreLon: 77.55 }]);
    expect(isSelectedNodeOutOfView(node, MOCK_MAP_BBOX)).toBe(false);
  });

  it('3. clicking Recenter uses the same hierarchy extent used by visibility', () => {
    const node = makeNode(13.0, 77.6, [{ centreLat: 13.15, centreLon: 77.8 }]);
    const intent = getCameraIntentForRecenter(node);
    const extent = getHierarchyExtent(node);

    expect(intent).not.toBeNull();
    expect(intent!.cameraBounds).toEqual([[extent!.minLat, extent!.minLon], [extent!.maxLat, extent!.maxLon]]);
    expect(intent!.centre).toEqual([(extent!.minLat + extent!.maxLat) / 2, (extent!.minLon + extent!.maxLon) / 2]);
  });

  it('4. after Recenter, relevant direct children are framed rather than just the selected node', () => {
    // The bounds generated by getCameraIntentForRecenter should encapsulate both the parent bounds and the child's location
    const node = makeNode(13.0, 77.6, [{ centreLat: 13.5, centreLon: 78.0 }]);
    const intent = getCameraIntentForRecenter(node);
    
    // Parent bounds are [12.99, 77.59] to [13.01, 77.61]
    // Child is at 13.5, 78.0
    // So bounds must be minLat 12.99, minLon 77.59, maxLat 13.5, maxLon 78.0
    expect(intent!.cameraBounds[0][0]).toBeLessThanOrEqual(12.99);
    expect(intent!.cameraBounds[0][1]).toBeLessThanOrEqual(77.59);
    expect(intent!.cameraBounds[1][0]).toBeGreaterThanOrEqual(13.5);
    expect(intent!.cameraBounds[1][1]).toBeGreaterThanOrEqual(78.0);
  });

  it('5. temporary clusterFocus does not replace/narrow the canonical Recenter extent', () => {
    // This is implicitly tested by the fact that `isSelectedNodeOutOfView` relies purely on `areasNavigationJourney.node`, 
    // which represents the canonical node, entirely bypassing any `clusterFocus` visual clustering state.
    // The UI handles this via the canonical `node` prop passed in.
    const canonicalNode = makeNode(13.0, 77.6, [{ centreLat: 12.95, centreLon: 77.55 }]);
    const intent = getCameraIntentForRecenter(canonicalNode);
    expect(intent).toBeDefined();
    // No reliance on cluster parameters.
  });
});
