-- V121: recursive-cluster navigation hierarchy schema + sandbox mirror (#1955 Areas PR A, SLICE 2a).
--
-- ADDITIVE ONLY. Creates TWO new tables (navigation_nodes production + sandbox_navigation_nodes
-- staging mirror, mirroring the V118 sandbox_* convention) and extends city_region_policy (V113)
-- with the recursive-cluster generator's policy knobs. SCHEMA + ENTITY + REPOSITORY PERSISTENCE
-- ONLY in this slice — no generator, no promotion, no cache, no counts, no endpoint reads or
-- writes this table yet (those are later, separately-scoped slices of #1955). Zero ALTER of any
-- existing production geography table other than the additive city_region_policy columns below;
-- zero touch of the live shopper read path.
--
-- ── navigation_nodes ─────────────────────────────────────────────────────────────────────────
-- One row per CLUSTER or AREA node in a city's navigation tree. `id` is a surrogate, FK-only
-- primary key — it is never exposed publicly; `node_key` is the stable public identity a future
-- endpoint slice will expose instead. AREA nodes are always leaves: enforced both by the CHECK
-- (node_type='AREA') = (area_key IS NOT NULL) AND by the trg_navigation_nodes_area_leaf trigger
-- below, which additionally rejects an AREA node ever being used as someone else's parent — the
-- CHECK alone cannot express that cross-row invariant.
--
-- `descendant_area_count` is a STRUCTURAL count of AREA leaves under this node — there is
-- deliberately NO listing_count column anywhere in this table; live listing volume is a
-- read-path concern for a later slice (cache/counts), never baked into the generated hierarchy
-- snapshot itself.
--
-- The composite self-FK (city_id, parent_node_id) -> navigation_nodes(city_id, id), backed by
-- the UNIQUE (city_id, id) constraint, makes cross-city parenting structurally impossible — a
-- node can only ever point at a parent row that shares its own city_id.

CREATE TABLE IF NOT EXISTS public.navigation_nodes (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id                     INTEGER NOT NULL REFERENCES public.cities (id),
    region_key                  TEXT NOT NULL,
    node_type                   TEXT NOT NULL CHECK (node_type IN ('CLUSTER', 'AREA')),
    parent_node_id              BIGINT NULL,
    node_key                    TEXT NOT NULL,
    area_key                    TEXT NULL REFERENCES public.areas (area_key),
    representative_area_keys    TEXT[] NOT NULL,
    display_label               TEXT NOT NULL,
    display_order               INTEGER NOT NULL,
    depth                       INTEGER NOT NULL CHECK (depth >= 0),
    ancestor_keys               TEXT[] NOT NULL,
    descendant_area_count       INTEGER NOT NULL,
    centre_lat                  NUMERIC NOT NULL,
    centre_lon                  NUMERIC NOT NULL,
    min_lat                     NUMERIC NOT NULL,
    min_lon                     NUMERIC NOT NULL,
    max_lat                     NUMERIC NOT NULL,
    max_lon                     NUMERIC NOT NULL,
    policy_fingerprint          TEXT NOT NULL,
    generated_at                TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_navigation_nodes_city_id UNIQUE (city_id, id),
    CONSTRAINT uq_navigation_nodes_city_node_key UNIQUE (city_id, node_key),
    CONSTRAINT chk_navigation_nodes_area_leaf CHECK ((node_type = 'AREA') = (area_key IS NOT NULL)),
    CONSTRAINT fk_navigation_nodes_parent FOREIGN KEY (city_id, parent_node_id)
        REFERENCES public.navigation_nodes (city_id, id)
);

-- One active AREA leaf per canonical area, per city.
CREATE UNIQUE INDEX IF NOT EXISTS uq_navigation_nodes_city_area
    ON public.navigation_nodes (city_id, area_key) WHERE node_type = 'AREA';

-- Direct-children read path: given a city + region + parent, return children in display order.
-- Also covers the root-node lookup (parent_node_id IS NULL) via the same index.
CREATE INDEX IF NOT EXISTS idx_navigation_nodes_children
    ON public.navigation_nodes (city_id, region_key, parent_node_id, display_order);

COMMENT ON TABLE public.navigation_nodes IS
    'Production recursive-cluster navigation tree (#1955 Areas PR A). One row per CLUSTER or AREA '
    'node. Schema + entity + repository ONLY in this slice; no generator/promotion/cache/counts '
    'service reads or writes this table yet.';
COMMENT ON COLUMN public.navigation_nodes.id IS
    'Surrogate FK-only primary key. Never exposed publicly — node_key is the stable public identity.';
COMMENT ON COLUMN public.navigation_nodes.ancestor_keys IS
    'Ordered root -> parent NODE_KEYS (not surrogate ids) for this node, for cheap breadcrumb '
    'rendering without a recursive query.';
COMMENT ON COLUMN public.navigation_nodes.descendant_area_count IS
    'Structural count of AREA leaves under this node. Deliberately NOT a listing count — live '
    'listing volume is a read-path concern for a later cache/counts slice, never baked into the '
    'generated hierarchy snapshot.';

CREATE OR REPLACE FUNCTION public.fn_reject_area_node_as_parent()
RETURNS trigger AS $$
DECLARE
    v_parent_type TEXT;
BEGIN
    IF NEW.parent_node_id IS NOT NULL THEN
        SELECT node_type INTO v_parent_type
        FROM public.navigation_nodes
        WHERE city_id = NEW.city_id AND id = NEW.parent_node_id;

        IF v_parent_type = 'AREA' THEN
            RAISE EXCEPTION
                'navigation_nodes.parent_node_id=% (city_id=%) refers to an AREA node — AREA nodes '
                'are always leaves and can never be a parent (#1955)',
                NEW.parent_node_id, NEW.city_id;
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_navigation_nodes_area_leaf ON public.navigation_nodes;
CREATE TRIGGER trg_navigation_nodes_area_leaf
    BEFORE INSERT OR UPDATE OF parent_node_id, city_id ON public.navigation_nodes
    FOR EACH ROW
    EXECUTE FUNCTION public.fn_reject_area_node_as_parent();

-- ── sandbox_navigation_nodes ─────────────────────────────────────────────────────────────────
-- Revision-scoped staging mirror of navigation_nodes, following the V118 sandbox_* convention:
-- scoped by revision_id (which already implies city via city_launch_revision.city_id) instead of
-- city_id. area_key is intentionally NOT a foreign key here — unlike the production table, a
-- sandbox row may describe an area that has not yet been promoted into public.areas. Insert+read
-- only, matching the rest of the sandbox_* family.

CREATE TABLE IF NOT EXISTS public.sandbox_navigation_nodes (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revision_id                 BIGINT NOT NULL REFERENCES public.city_launch_revision (id) ON DELETE CASCADE,
    region_key                  TEXT NOT NULL,
    node_type                   TEXT NOT NULL CHECK (node_type IN ('CLUSTER', 'AREA')),
    parent_node_id              BIGINT NULL,
    node_key                    TEXT NOT NULL,
    area_key                    TEXT NULL,
    representative_area_keys    TEXT[] NOT NULL,
    display_label               TEXT NOT NULL,
    display_order               INTEGER NOT NULL,
    depth                       INTEGER NOT NULL CHECK (depth >= 0),
    ancestor_keys               TEXT[] NOT NULL,
    descendant_area_count       INTEGER NOT NULL,
    centre_lat                  NUMERIC NOT NULL,
    centre_lon                  NUMERIC NOT NULL,
    min_lat                     NUMERIC NOT NULL,
    min_lon                     NUMERIC NOT NULL,
    max_lat                     NUMERIC NOT NULL,
    max_lon                     NUMERIC NOT NULL,
    policy_fingerprint          TEXT NOT NULL,
    generated_at                TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_sandbox_navigation_nodes_revision_id UNIQUE (revision_id, id),
    CONSTRAINT uq_sandbox_navigation_nodes_revision_node_key UNIQUE (revision_id, node_key),
    CONSTRAINT chk_sandbox_navigation_nodes_area_leaf CHECK ((node_type = 'AREA') = (area_key IS NOT NULL)),
    CONSTRAINT fk_sandbox_navigation_nodes_parent FOREIGN KEY (revision_id, parent_node_id)
        REFERENCES public.sandbox_navigation_nodes (revision_id, id)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_sandbox_navigation_nodes_revision_area
    ON public.sandbox_navigation_nodes (revision_id, area_key) WHERE node_type = 'AREA';

CREATE INDEX IF NOT EXISTS idx_sandbox_navigation_nodes_revision_id
    ON public.sandbox_navigation_nodes (revision_id);

COMMENT ON TABLE public.sandbox_navigation_nodes IS
    'Revision-scoped staging mirror of public.navigation_nodes (#1955 Areas PR A). Insert+read '
    'only. area_key is NOT a foreign key (unlike the production table) — a sandbox row may '
    'describe an area not yet promoted into public.areas.';

CREATE OR REPLACE FUNCTION public.fn_reject_sandbox_area_node_as_parent()
RETURNS trigger AS $$
DECLARE
    v_parent_type TEXT;
BEGIN
    IF NEW.parent_node_id IS NOT NULL THEN
        SELECT node_type INTO v_parent_type
        FROM public.sandbox_navigation_nodes
        WHERE revision_id = NEW.revision_id AND id = NEW.parent_node_id;

        IF v_parent_type = 'AREA' THEN
            RAISE EXCEPTION
                'sandbox_navigation_nodes.parent_node_id=% (revision_id=%) refers to an AREA node — '
                'AREA nodes are always leaves and can never be a parent (#1955)',
                NEW.parent_node_id, NEW.revision_id;
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_sandbox_navigation_nodes_area_leaf ON public.sandbox_navigation_nodes;
CREATE TRIGGER trg_sandbox_navigation_nodes_area_leaf
    BEFORE INSERT OR UPDATE OF parent_node_id, revision_id ON public.sandbox_navigation_nodes
    FOR EACH ROW
    EXECUTE FUNCTION public.fn_reject_sandbox_area_node_as_parent();

-- ── city_region_policy: recursive-cluster generator knobs (D1: policy values are DATA) ────────
-- All nullable/defaulted — existing rows (bangalore, udupi from V113) get the placeholder
-- calibration seeded below rather than being left NULL, so a future generator service has a
-- deterministic, testable policy to read from day one. These are PLACEHOLDER DEFAULT values, not
-- geography-tuned numbers — real per-city calibration is a product-data follow-up, tracked
-- separately from this schema slice.

ALTER TABLE public.city_region_policy
    ADD COLUMN IF NOT EXISTS max_direct_children       INTEGER,
    ADD COLUMN IF NOT EXISTS min_areas_per_cluster      INTEGER,
    ADD COLUMN IF NOT EXISTS max_safety_depth           INTEGER,
    ADD COLUMN IF NOT EXISTS one_child_prevention       BOOLEAN,
    ADD COLUMN IF NOT EXISTS compactness_threshold      NUMERIC,
    ADD COLUMN IF NOT EXISTS separation_threshold       NUMERIC,
    ADD COLUMN IF NOT EXISTS partition_method           TEXT DEFAULT 'GEOMETRIC_BISECTION',
    ADD COLUMN IF NOT EXISTS representative_selection   TEXT,
    ADD COLUMN IF NOT EXISTS outlier_rule                TEXT,
    ADD COLUMN IF NOT EXISTS centre_treatment            TEXT;

COMMENT ON COLUMN public.city_region_policy.max_direct_children IS
    'Recursive-cluster generator knob (#1955): max children a CLUSTER node may have before it is '
    'split further. PLACEHOLDER DEFAULT (see seed UPDATE below) pending product-data calibration.';
COMMENT ON COLUMN public.city_region_policy.min_areas_per_cluster IS
    'Recursive-cluster generator knob (#1955): minimum AREA leaves a CLUSTER must cover to remain '
    'its own node rather than being folded into a sibling. PLACEHOLDER DEFAULT.';
COMMENT ON COLUMN public.city_region_policy.max_safety_depth IS
    'Recursive-cluster generator knob (#1955): hard recursion-depth ceiling so a pathological '
    'geometry cannot recurse unbounded. PLACEHOLDER DEFAULT.';
COMMENT ON COLUMN public.city_region_policy.one_child_prevention IS
    'Recursive-cluster generator knob (#1955): when true, a split that would produce a single-child '
    'CLUSTER is rejected in favour of not splitting. PLACEHOLDER DEFAULT.';
COMMENT ON COLUMN public.city_region_policy.compactness_threshold IS
    'Recursive-cluster generator knob (#1955): minimum shape-compactness a candidate cluster must '
    'meet to be accepted as-is rather than re-partitioned. PLACEHOLDER DEFAULT.';
COMMENT ON COLUMN public.city_region_policy.separation_threshold IS
    'Recursive-cluster generator knob (#1955): minimum inter-cluster separation required for a '
    'partition to be accepted. PLACEHOLDER DEFAULT.';
COMMENT ON COLUMN public.city_region_policy.partition_method IS
    'Recursive-cluster generator knob (#1955): the partitioning strategy applied at each recursion '
    'level. Defaults to GEOMETRIC_BISECTION for every existing/future row.';
COMMENT ON COLUMN public.city_region_policy.representative_selection IS
    'Recursive-cluster generator knob (#1955): how a CLUSTER node''s representative_area_keys are '
    'chosen from its descendant areas. PLACEHOLDER DEFAULT.';
COMMENT ON COLUMN public.city_region_policy.outlier_rule IS
    'Recursive-cluster generator knob (#1955): how an area geometrically isolated from its '
    'siblings is attached during partitioning. PLACEHOLDER DEFAULT.';
COMMENT ON COLUMN public.city_region_policy.centre_treatment IS
    'Recursive-cluster generator knob (#1955): how a node''s centre_lat/centre_lon are derived from '
    'its member areas. PLACEHOLDER DEFAULT.';

-- Seed placeholder defaults for every existing city_region_policy row (idempotent via COALESCE —
-- never overwrites a value an operator has already set). A future generator service's
-- policy_fingerprint recipe is expected to extend CityRegionOnboardingService.computeFingerprint's
-- existing "join every policy-shaping input with '|', sha256 it" recipe (V113) to additionally
-- fold in these ten knobs — documented here as the contract for that later slice, not implemented
-- by it yet (no generator ships in this migration).
UPDATE public.city_region_policy
SET max_direct_children      = COALESCE(max_direct_children, 8),
    min_areas_per_cluster     = COALESCE(min_areas_per_cluster, 3),
    max_safety_depth          = COALESCE(max_safety_depth, 6),
    one_child_prevention      = COALESCE(one_child_prevention, true),
    compactness_threshold     = COALESCE(compactness_threshold, 0.35),
    separation_threshold      = COALESCE(separation_threshold, 0.5),
    partition_method          = COALESCE(partition_method, 'GEOMETRIC_BISECTION'),
    representative_selection  = COALESCE(representative_selection, 'CENTROID_NEAREST'),
    outlier_rule              = COALESCE(outlier_rule, 'ATTACH_NEAREST_CLUSTER'),
    centre_treatment          = COALESCE(centre_treatment, 'AREA_CENTROID_MEAN');
