-- V125: revision-scoped Agricultural destination classification (#2151 PR A, decision.d2).
--
-- ADDITIVE ONLY. Creates TWO new tables:
--   sandbox_agri_destination_classification — revision-scoped staging mirror, following the V118
--     sandbox_* convention (scoped by revision_id, which already implies city via
--     city_launch_revision.city_id).
--   agri_destination_classification         — production table, scoped by city_id, FK to
--     public.areas(area_key).
--
-- This SUPERSEDES public.regional_area_classifications (V87) as the production read source for the
-- Agricultural destination journey — but does NOT modify, delete, or read from that table in this
-- migration or this PR. regional_area_classifications keeps computing exactly what it always has;
-- the cutover to this new table is PR B's job (#2151 decision.d4).
--
-- WHY A NEW TABLE RATHER THAN ADDING revision_id TO regional_area_classifications: that table has
-- NO FK to cities (V87:69-73, by design — city_key is a slug) and is keyed PRIMARY KEY
-- (city_key, area_key), i.e. one row per (city, area) with no revision axis at all. Retrofitting a
-- revision_id onto it would require dropping and rebuilding its primary key and rewriting its sole
-- writer (RegionalClassificationBackfillService) and its ApplicationRunner trigger — none of which
-- this PR touches (forbidden — see #2151 PR A scope).
--
-- ORIGIN SNAPSHOT (decision.d2): origin_lat/origin_lon are NOT NULL on every row — the city's
-- cities.geo_center_lat/lon at PREPARE time, snapshotted into EVERY row, so a revision is fully
-- self-describing and a later edit to cities.geo_center_lat/lon cannot retroactively invalidate an
-- already-PREPARED or already-PROMOTED revision's classification.
--
-- STALE-ROW DISCIPLINE (F2 closure): unlike regional_area_classifications' no-delete upsert
-- (RegionalClassificationBackfillService), both the generator (sandbox, on regeneration) and the
-- promotion step (production, via REPLACE discipline mirroring promoteNavigationNodes) DELETE the
-- prior row set before writing the new one — an area renamed/merged/made INACTIVE cannot leave an
-- orphaned classification row behind.
--
-- Rollback (manual, not run automatically):
--   DROP TABLE IF EXISTS public.agri_destination_classification;
--   DROP TABLE IF EXISTS public.sandbox_agri_destination_classification;

-- ── sandbox_agri_destination_classification ─────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS public.sandbox_agri_destination_classification (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revision_id        BIGINT NOT NULL REFERENCES public.city_launch_revision (id) ON DELETE CASCADE,
    area_key           TEXT NOT NULL,
    origin_lat         DOUBLE PRECISION NOT NULL,
    origin_lon         DOUBLE PRECISION NOT NULL,
    distance_km        DOUBLE PRECISION NOT NULL,
    bearing_deg        DOUBLE PRECISION NOT NULL,
    direction_key      TEXT NOT NULL REFERENCES public.regional_directions (direction_key),
    distance_band_key  TEXT NOT NULL REFERENCES public.regional_distance_bands (band_key),
    generator_version  TEXT NOT NULL,
    generated_at       TIMESTAMPTZ,
    UNIQUE (revision_id, area_key)
);

CREATE INDEX IF NOT EXISTS idx_sandbox_agri_destination_classification_revision_id
    ON public.sandbox_agri_destination_classification (revision_id);

COMMENT ON TABLE public.sandbox_agri_destination_classification IS
    'Revision-scoped staging mirror of the Agricultural destination direction/distance '
    'classification (#2151 PR A). Insert+read only; a row is never mutated after insert (matches '
    'the V118 sandbox_* family convention). area_key is NOT a foreign key here — unlike the '
    'production table, a sandbox row may describe an area not yet promoted into public.areas.';
COMMENT ON COLUMN public.sandbox_agri_destination_classification.origin_lat IS
    'City geo_center_lat AT PREPARE TIME, snapshotted into every row so the revision is '
    'self-describing and a later edit to cities.geo_center_lat cannot retroactively invalidate an '
    'already-prepared revision (#2151 decision.d2).';
COMMENT ON COLUMN public.sandbox_agri_destination_classification.origin_lon IS
    'City geo_center_lon AT PREPARE TIME, snapshotted into every row — see origin_lat comment.';
COMMENT ON COLUMN public.sandbox_agri_destination_classification.generator_version IS
    'Provenance tag identifying which generator revision produced this row (#2151 decision.d2 '
    'required_columns item (d): source/provenance/version).';

-- ── agri_destination_classification (production) ────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS public.agri_destination_classification (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id            INTEGER NOT NULL REFERENCES public.cities (id),
    area_key           TEXT NOT NULL REFERENCES public.areas (area_key),
    origin_lat         DOUBLE PRECISION NOT NULL,
    origin_lon         DOUBLE PRECISION NOT NULL,
    distance_km        DOUBLE PRECISION NOT NULL,
    bearing_deg        DOUBLE PRECISION NOT NULL,
    direction_key      TEXT NOT NULL REFERENCES public.regional_directions (direction_key),
    distance_band_key  TEXT NOT NULL REFERENCES public.regional_distance_bands (band_key),
    generator_version  TEXT NOT NULL,
    generated_at       TIMESTAMPTZ,
    UNIQUE (city_id, area_key)
);

CREATE INDEX IF NOT EXISTS idx_agri_destination_classification_city_id
    ON public.agri_destination_classification (city_id);

COMMENT ON TABLE public.agri_destination_classification IS
    'Production Agricultural destination direction/distance classification (#2151 PR A). Written '
    'ONLY by CityLaunchPromotionService.promoteAgriDestinationClassification, via REPLACE '
    'discipline (delete-by-city-id then insert) mirroring promoteNavigationNodes. NOT READ by any '
    'production path in PR A — this table is written and unread by design until PR B cuts '
    'RegionalAreaGroupsService over to it (#2151 decision.d4).';
COMMENT ON COLUMN public.agri_destination_classification.origin_lat IS
    'City geo_center_lat as of the PROMOTED revision''s prepare time — see sandbox table comment '
    'for the self-describing-revision rationale.';

-- ── city_launch_revision: 6th validation checklist column (#2151 PR A, mirrors V120) ────────────
--
-- ADDITIVE ONLY. Adds a sixth per-check validation flag alongside the five V120 columns
-- (landing_validated, regions_validated, area_groups_validated, areas_validated,
-- listing_validated), following the exact same guarded-write/demotion-CASE discipline. No backfill
-- needed — every existing row gets the DEFAULT false value.
--
-- STRANDED IN-FLIGHT REVISIONS (correction pass finding #2): the DEFAULT false VALUE is correct for
-- every existing row, but a revision already in PREPARED lifecycle_status at deploy time has a
-- REACHABILITY problem, not a value problem. Such a revision was generated before this migration's
-- sandbox_agri_destination_classification table existed, so it has ZERO rows there.
-- setAgriValidatedTrue's WHERE clause requires an EXISTS match against
-- sandbox_agri_destination_classification (AC2), which a zero-row revision can never satisfy, so
-- agri_validated can never be set to true for it and markValidated's six-column WHERE clause can
-- therefore never match either — the revision is permanently stuck in PREPARED. This is NOT fixed by
-- this migration (a backfill would fabricate an admin attestation that never happened, and relaxing
-- the EXISTS guard would defeat AC2) and does NOT need to be: the operator recovery path is
-- CityLaunchPreparationService#rerunSuperseding, which supersedes the stranded revision with a
-- fresh one that runs through the current prepare pipeline (and therefore does get
-- sandbox_agri_destination_classification rows). Document this for the deploying operator; no other
-- action is required by this migration.
--
-- Rollback (manual, not run automatically):
--   ALTER TABLE public.city_launch_revision DROP COLUMN IF EXISTS agri_validated;

ALTER TABLE public.city_launch_revision
    ADD COLUMN IF NOT EXISTS agri_validated BOOLEAN NOT NULL DEFAULT false;

COMMENT ON COLUMN public.city_launch_revision.agri_validated IS
    'Admin has manually confirmed the Agricultural destination classification preview for this '
    'revision looks correct (#2151 PR A validation checklist, mirrors V120''s five columns). '
    'Written only via CityLaunchRevisionRepository''s guarded @Modifying queries, never via '
    'save() — see setAgriValidatedTrue/False and markValidated''s WHERE clause, which is the SOLE '
    'promotability authority (never a Java pre-check).';
