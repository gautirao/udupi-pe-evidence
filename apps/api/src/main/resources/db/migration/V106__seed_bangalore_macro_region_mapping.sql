-- ── 5. Invariant guard: no Bangalore locality may belong to more than one group ──────
-- Fails fast (in Testcontainers and on deploy) if a future edit reintroduces an overlap.
-- Scoped to bangalore only — other cities (Udupi) are out of scope for this issue.

DO $$
DECLARE
    dup_count INTEGER;
BEGIN
    SELECT COUNT(*) INTO dup_count
    FROM (
        SELECT agm.area_key
        FROM public.area_group_members agm
        JOIN public.area_groups ag ON ag.id = agm.area_group_id
        JOIN public.cities c ON c.id = ag.city_id
        WHERE c.slug = 'bangalore'
        GROUP BY agm.area_key
        HAVING COUNT(*) > 1
    ) dups;

    IF dup_count > 0 THEN
        RAISE EXCEPTION 'V106 invariant violated: % bangalore area_key(s) belong to more than one area_group', dup_count;
    END IF;
END $$;
