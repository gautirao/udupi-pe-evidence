-- V118: city launch revision lifecycle + sandbox geography staging (#1911 PR1).
--
-- ADDITIVE ONLY. This migration creates ONE new parent table (city_launch_revision) and SIX
-- new revision-scoped sandbox tables. It performs ZERO ALTER of any existing production
-- geography table (cities, areas, area_groups, area_group_members, city_regions,
-- city_region_memberships, city_region_policy, regional_*). Mirrors the V115/V113
-- "expand-only, staging-table" convention used by #1887/#1882.
--
-- SCOPE: schema + entity + repository persistence ONLY. No promotion/apply logic, no
-- lifecycle-transition service, no scheduled/async orchestration ships in this PR — those are
-- PR8+ concerns. The only UPDATE surface introduced here is a guarded supersession/lifecycle
-- transition on city_launch_revision itself; every sandbox_* table is insert+read in the Java
-- layer (see the corresponding Repository interfaces).
--
-- FIELD-MAPPING RATIONALE (pipeline output -> sandbox field -> preview consumer -> promotion
-- consumer), so future drift from this mapping is a conscious decision, not an accident:
--   * sandbox_areas mirrors public.areas (V71) column-for-column (area_key, name, district,
--     geo_center_lat/lon, min/max_lat/lon as DOUBLE PRECISION, geometry_source, osm_element_*).
--     Preview consumer: PR-N admin preview map renders sandbox_areas the same way Discover
--     renders public.areas. Promotion consumer: a future PR8 promotion step copies
--     sandbox_areas rows verbatim into public.areas, so the column set and types are chosen to
--     require zero transformation at promotion time.
--   * sandbox_area_aliases mirrors public.area_alias (V115) (alias, alias_normalised),
--     scoped by revision_id instead of city_id (a revision is already city-scoped via its
--     parent city_launch_revision.city_id).
--   * sandbox_city_regions mirrors public.city_regions (V113) column-for-column, INCLUDING the
--     NUMERIC geo column types (not DOUBLE PRECISION) — V113 deliberately uses NUMERIC for
--     city_regions geometry, unlike V71's areas/DOUBLE PRECISION, and this table must match its
--     promotion target exactly.
--   * sandbox_city_region_memberships mirrors public.city_region_memberships (V113)
--     (region_key, assignment_source), scoped to a sandbox_area_id instead of an area_key.
--   * sandbox_area_groups mirrors public.area_groups (V77) column-for-column, including the
--     DOUBLE PRECISION focus_lat/lon and min/max_lat/lon geo columns (V77 matches V71's type
--     choice, unlike V113).
--   * sandbox_area_group_members mirrors public.area_group_members (V77) (display_order),
--     scoped to sandbox_area_group_id + sandbox_area_id surrogate keys instead of area_key.
--
-- created_by is a soft Supabase auth UUID reference with NO foreign key and NO RLS policy on
-- any table in this migration — this matches the existing Listing.createdBy precedent and the
-- broader cities/areas/area_groups/city_region_*/area_onboarding_* table family, which is
-- entirely server-authz'd via @IsAdmin at the (PR2+) endpoint layer, not via RLS. Adding either
-- here would be scope expansion inconsistent with the family (orchestrator decision, #1911 PR1).

-- ── city_launch_revision ─────────────────────────────────────────────────────────────────────
-- One row per city launch/re-launch attempt. Tracks the full prep -> validate -> promote ->
-- supersede lifecycle for a city's geography dataset. Never mutates public geography directly;
-- promotion (PR8+) reads FROM a PROMOTED revision's sandbox_* rows and writes them into public
-- geography tables in a separate, explicit apply step.

CREATE TABLE IF NOT EXISTS public.city_launch_revision (
    id                            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id                       INTEGER NOT NULL REFERENCES public.cities (id),
    revision_number               INTEGER NOT NULL,
    lifecycle_status              TEXT NOT NULL DEFAULT 'PREPARING'
                                      CHECK (lifecycle_status IN (
                                          'PREPARING', 'PREPARED', 'VALIDATED', 'PROMOTING',
                                          'PROMOTED', 'SUPERSEDED', 'FAILED'
                                      )),
    source_batch_id               BIGINT NULL REFERENCES public.area_onboarding_batch (id),
    dataset_id                    TEXT,
    dataset_version               TEXT,
    source_artifact_checksum      TEXT,
    region_model                  TEXT,
    central_radius_km             NUMERIC,
    prep_stage                    SMALLINT NOT NULL DEFAULT 0 CHECK (prep_stage BETWEEN 0 AND 6),
    prep_state                    TEXT NOT NULL DEFAULT 'PENDING'
                                      CHECK (prep_state IN ('PENDING', 'RUNNING', 'DONE', 'FAILED')),
    validation_status             TEXT,
    persisted_revision_checksum   TEXT,
    applied_revision_checksum     TEXT,
    created_by                    UUID,
    created_at                    TIMESTAMPTZ NOT NULL DEFAULT now(),
    prepared_at                   TIMESTAMPTZ,
    promoted_at                   TIMESTAMPTZ,
    failure_reason                TEXT,
    superseded_by                 BIGINT NULL REFERENCES public.city_launch_revision (id),
    UNIQUE (city_id, revision_number)
);

-- At most one in-flight (non-terminal, pre-promotion) revision per city at a time.
CREATE UNIQUE INDEX IF NOT EXISTS uq_clr_inflight
    ON public.city_launch_revision (city_id)
    WHERE lifecycle_status IN ('PREPARING', 'PREPARED', 'VALIDATED', 'PROMOTING');

-- At most one currently-live PROMOTED revision (not yet superseded) per city at a time.
CREATE UNIQUE INDEX IF NOT EXISTS uq_clr_current_promoted
    ON public.city_launch_revision (city_id)
    WHERE lifecycle_status = 'PROMOTED' AND superseded_by IS NULL;

COMMENT ON TABLE public.city_launch_revision IS
    'One row per city launch/re-launch lifecycle attempt (#1911 PR1). Owns the prep -> validate '
    '-> promote -> supersede state machine. Never itself alters public geography tables; a '
    'future promotion step (PR8+) reads a PROMOTED revision''s sandbox_* rows and writes them '
    'into public geography in a separate transaction.';
COMMENT ON COLUMN public.city_launch_revision.created_by IS
    'Soft Supabase auth uid reference, deliberately NOT a foreign key (matches Listing.createdBy '
    'precedent) — this table family is server-authz''d via @IsAdmin at the endpoint layer, not RLS.';
COMMENT ON COLUMN public.city_launch_revision.source_batch_id IS
    'Optional soft link to the area_onboarding_batch (#1887) this revision was seeded from, when '
    'the revision''s areas originated from an onboarding dry-run/apply batch.';
COMMENT ON COLUMN public.city_launch_revision.prep_stage IS
    'Monotonic 0..6 progress counter through the offline prep pipeline stages; bounds enforced '
    'by CHECK so a runaway/miscoded stage index cannot silently persist.';
COMMENT ON COLUMN public.city_launch_revision.persisted_revision_checksum IS
    'Checksum of the sandbox_* row set as PERSISTED at prep completion — the "before" anchor.';
COMMENT ON COLUMN public.city_launch_revision.applied_revision_checksum IS
    'Checksum of the sandbox_* row set as READ at promotion time — the "after" anchor; a future '
    'promotion step compares this against persisted_revision_checksum to detect drift between '
    'prep completion and promotion.';
COMMENT ON COLUMN public.city_launch_revision.superseded_by IS
    'Self-referencing pointer to the revision that superseded this one, set atomically with the '
    'SUPERSEDED transition in the same transaction that promotes the new revision.';

-- ── sandbox_areas ────────────────────────────────────────────────────────────────────────────
-- Revision-scoped staging mirror of public.areas (V71). Column types match the V71 promotion
-- target (DOUBLE PRECISION geometry) exactly.

CREATE TABLE IF NOT EXISTS public.sandbox_areas (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revision_id        BIGINT NOT NULL REFERENCES public.city_launch_revision (id) ON DELETE CASCADE,
    area_key           TEXT,
    name               TEXT,
    district           TEXT,
    geo_center_lat     DOUBLE PRECISION,
    geo_center_lon     DOUBLE PRECISION,
    min_lat            DOUBLE PRECISION,
    min_lon            DOUBLE PRECISION,
    max_lat            DOUBLE PRECISION,
    max_lon            DOUBLE PRECISION,
    geometry_source    TEXT,
    osm_element_type   TEXT,
    osm_element_id     BIGINT,
    lifecycle_status   TEXT NOT NULL DEFAULT 'ACTIVE',
    UNIQUE (revision_id, area_key)
);

CREATE INDEX IF NOT EXISTS idx_sandbox_areas_revision_id
    ON public.sandbox_areas (revision_id);

COMMENT ON TABLE public.sandbox_areas IS
    'Revision-scoped staging mirror of public.areas (V71) — #1911 PR1. Insert+read only; a '
    'sandbox_areas row is never mutated after insert. Promotion (PR8+) copies these rows into '
    'public.areas verbatim, so the column set/types intentionally match V71 exactly.';
COMMENT ON COLUMN public.sandbox_areas.lifecycle_status IS
    'Mirrors public.areas.lifecycle_status semantics for preview rendering; not CHECK-constrained '
    'in PR1 pending the value set carried over from the source onboarding pipeline.';

-- ── sandbox_area_aliases ─────────────────────────────────────────────────────────────────────
