    UNIQUE (revision_id, sandbox_area_id)
);

CREATE INDEX IF NOT EXISTS idx_sandbox_city_region_memberships_revision_id
    ON public.sandbox_city_region_memberships (revision_id);

COMMENT ON TABLE public.sandbox_city_region_memberships IS
    'Revision-scoped staging mirror of public.city_region_memberships (V113) — #1911 PR1. '
    'Insert+read only. One membership row per sandbox area within a revision.';

-- ── sandbox_area_groups ──────────────────────────────────────────────────────────────────────
