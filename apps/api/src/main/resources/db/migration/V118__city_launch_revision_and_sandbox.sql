CREATE INDEX IF NOT EXISTS idx_sandbox_area_group_members_revision_id
    ON public.sandbox_area_group_members (revision_id);

COMMENT ON TABLE public.sandbox_area_group_members IS
    'Revision-scoped staging mirror of public.area_group_members (V77) — #1911 PR1. Insert+read '
    'only. Cascades on BOTH sandbox_area_group_id and sandbox_area_id, so deleting the parent '
    'revision (which cascades to sandbox_areas and sandbox_area_groups) removes every membership '
    'row via either path with no orphans left behind.';
