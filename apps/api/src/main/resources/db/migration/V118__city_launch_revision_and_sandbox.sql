    focus_lat         DOUBLE PRECISION,
    focus_lon         DOUBLE PRECISION,
    min_lat           DOUBLE PRECISION,
    min_lon           DOUBLE PRECISION,
    max_lat           DOUBLE PRECISION,
    max_lon           DOUBLE PRECISION,
    UNIQUE (revision_id, slug)
);

CREATE INDEX IF NOT EXISTS idx_sandbox_area_groups_revision_id
    ON public.sandbox_area_groups (revision_id);

COMMENT ON TABLE public.sandbox_area_groups IS
    'Revision-scoped staging mirror of public.area_groups (V77) — #1911 PR1. Insert+read only.';

-- ── sandbox_area_group_members ───────────────────────────────────────────────────────────────
-- Revision-scoped staging mirror of public.area_group_members (V77).

CREATE TABLE IF NOT EXISTS public.sandbox_area_group_members (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revision_id               BIGINT NOT NULL REFERENCES public.city_launch_revision (id) ON DELETE CASCADE,
    sandbox_area_group_id     BIGINT NOT NULL REFERENCES public.sandbox_area_groups (id) ON DELETE CASCADE,
    sandbox_area_id           BIGINT NOT NULL REFERENCES public.sandbox_areas (id) ON DELETE CASCADE,
    display_order             INTEGER,
    UNIQUE (sandbox_area_group_id, sandbox_area_id)
