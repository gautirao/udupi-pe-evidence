    min_lon              NUMERIC,
    max_lat              NUMERIC,
    max_lon              NUMERIC,
    policy_fingerprint   TEXT,
    UNIQUE (revision_id, region_key)
);

CREATE INDEX IF NOT EXISTS idx_sandbox_city_regions_revision_id
    ON public.sandbox_city_regions (revision_id);

COMMENT ON TABLE public.sandbox_city_regions IS
    'Revision-scoped staging mirror of public.city_regions (V113) — #1911 PR1. Insert+read only. '
    'Geometry columns are NUMERIC (not DOUBLE PRECISION) to match V113''s promotion target exactly.';

-- ── sandbox_city_region_memberships ──────────────────────────────────────────────────────────
-- Revision-scoped staging mirror of public.city_region_memberships (V113).

CREATE TABLE IF NOT EXISTS public.sandbox_city_region_memberships (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revision_id          BIGINT NOT NULL REFERENCES public.city_launch_revision (id) ON DELETE CASCADE,
