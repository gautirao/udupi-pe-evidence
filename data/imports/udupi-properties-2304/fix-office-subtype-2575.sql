-- fix-office-subtype-2575.sql
--
-- Issue #2575 (Part B): corrects five LIVE 99acres office listings that were
-- imported as property_type='commercial_building' / commercial_subtype='BUILDING'
-- instead of property_type='commercial' / commercial_subtype='OFFICE'.
--
-- Root cause: listing_commercial_building_details (lcbd) has no
-- commercial_subtype column -- only listing_commercial_space_details (lcsd)
-- does. An OFFICE listing routed through the commercial_building/lcbd path is
-- therefore structurally unrepresentable. This script moves each affected
-- listing's flat property_type/commercial_subtype AND its detail row from
-- lcbd to lcsd.
--
-- THIS SCRIPT DOES NOT EXECUTE ANYTHING AGAINST ANY DATABASE. It is produced
-- as a reviewable artifact only. Deployment/execution is the owner's
-- responsibility.
--
-- SCOPE BEYOND THE NOMINAL COLUMN FIX -- read before running:
-- In addition to the property_type/commercial_subtype correction this script
-- is nominally about, step 1 below ALSO writes an audit object into
-- property_listings.parsed_data under the key 'fix2575RollbackAudit', on
-- each of the five rows listed below. This audit object exists so a later,
-- separate rollback script (fix-office-subtype-2575-rollback.sql) can
-- restore the exact pre-correction state without guessing at it. It holds
-- only operational metadata captured from this correction's own pre-image
-- (prior lcsd presence/subtype, prior lcbd detail values) -- no PII.
-- property_listings.parsed_data is on the anon-SELECT allow-list, i.e. it is
-- readable by unauthenticated clients, so this audit object is publicly
-- visible for as long as it remains on these rows. Two companion scripts
-- manage its lifecycle: fix-office-subtype-2575-rollback.sql clears it on
-- rollback, and cleanup-audit-2575.sql (Part B, run only when no rollback
-- will ever be needed) clears it on the normal/no-rollback path.
--
-- The five row ids this script -- and therefore this audit write -- affects:
-- M91395690, Z59660870, D90432306, U90462182, W88736208 (99acres source ids;
-- see fix_2575_targets below for their derived listing UUIDs).
--
-- Idempotent: safe to run more than once. Steps 1-3 are each scoped by the
-- same WHERE clause -- including a "still in the old (BUILDING) state" gate
-- -- so on a second run that clause matches zero rows. Step 4's DELETE
-- cannot reuse that same WHERE clause directly (by the time it runs, step 3
-- has already moved property_type off 'commercial_building', so the gate
-- would always match zero rows, even on a fresh run); instead it is scoped
-- to fix_2575_captured, the id set step 1's WHERE clause actually matched
-- this run. That set is empty on a second run, so step 4 also touches zero
-- rows then. Net effect: a second run touches zero rows across all four
-- mutating steps and is a true no-op, not a second mutation.
--
-- import.sql is NOT regenerated by this script and is NOT touched by it.
-- normalise_v2.py's mapping fix (the root-cause fix for issue #2575) only
-- changes what a FUTURE normalise run produces; the five live rows here came
-- from the PREVIOUS run, whose output fed the existing import.sql. Measured:
-- import.sql contains zero `DO UPDATE` and zero `EXCLUDED` references; all
-- 104 property_listings inserts use `ON CONFLICT (id) DO NOTHING`, and the
-- detail-table inserts use `ON CONFLICT (listing_id) DO NOTHING` (12
-- occurrences). So re-running import.sql against a database this script has
-- already corrected cannot revert these five rows -- the DO NOTHING clauses
-- make every insert for an id already present a no-op. The one residual
-- risk this does NOT cover: if one of the five corrected rows were later
-- deleted outright and then re-imported, it would come back in the pre-fix
-- commercial_building/BUILDING shape, because import.sql and
-- normalised-listings.json still encode that shape for these ids. Neither
-- artefact is regenerated here; doing so from the now-fixed normalise_v2.py
-- is the durable resolution, and is deliberately out of scope for this
-- correction.
--
-- Ordering within the single transaction:
--   1. capture pre-image / write rollback-audit data into parsed_data
--   2. UPSERT the lcsd row (never DO NOTHING -- see inline comment)
--   3. UPDATE property_listings flat columns to commercial/OFFICE
--   4. DELETE the now-stale lcbd row
--   5. assert post-conditions
-- Steps 2 and 3 are NOT order-dependent on each other, despite an earlier
-- version of this comment claiming otherwise. The V135 constraint trigger
-- that validates "every property_type='commercial' row has a matching lcsd
-- projection" is DEFERRABLE INITIALLY DEFERRED. For the full mechanism --
-- which of the two triggers involved fires eagerly vs. unconditionally, and
-- why the queued check early-returns by COMMIT -- see the canonical
-- comment in fix-office-subtype-2575-rollback.sql, immediately above its
-- BEGIN. What matters here is only that, by COMMIT, both writes have
-- landed within the same transaction -- statement order inside it is not
-- observable to the trigger. The real ordering dependencies in this script
-- are elsewhere, and there are two of them:
--   1. step 1 must precede step 4, because step 4's DELETE destroys the
--      lcbd row's values (including created_at) that step 1 needs to
--      capture into the rollback audit payload first.
--   2. step 1 must precede step 4 for a second, independent reason: step 1
--      populates fix_2575_captured (via its RETURNING clause), which step
--      4's DELETE is scoped to -- if step 4 ran first, that set would still
--      be empty and the DELETE would remove nothing.

BEGIN;

-- Five affected 99acres listing ids, matched via import.sql's own identity
-- derivation: (md5('99acres:' || id))::uuid. Deriving the UUID here (rather
-- than pasting a pre-computed literal) means a transcription slip in the id
-- list below is visible in the source text itself, instead of silently
-- shrinking the matched set via a wrong literal.
CREATE TEMP TABLE fix_2575_targets (listing_99acres_id text, listing_id uuid) ON COMMIT DROP;
INSERT INTO fix_2575_targets (listing_99acres_id, listing_id)
VALUES
  ('M91395690', (md5('99acres:' || 'M91395690'))::uuid),
  ('Z59660870', (md5('99acres:' || 'Z59660870'))::uuid),
  ('D90432306', (md5('99acres:' || 'D90432306'))::uuid),
  ('U90462182', (md5('99acres:' || 'U90462182'))::uuid),
  ('W88736208', (md5('99acres:' || 'W88736208'))::uuid);

-- Holds the ids step 1 ACTUALLY matched and captured (not the full target
-- list) -- populated by step 1's RETURNING clause below. Step 4's DELETE is
-- scoped to this set, not to fix_2575_targets, so it stays in lockstep with
-- the same old-state gate step 1 applies, even though the flat-column
-- UPDATE in step 3 has already moved property_type off 'commercial_building'
-- by the time step 4 runs (see step 4's comment for why joining that gate
-- directly there would not work).
CREATE TEMP TABLE fix_2575_captured (listing_id uuid) ON COMMIT DROP;

-- Gate 1+2 (identity + provenance) count assertion. This is time-invariant:
-- it does not depend on whether the correction already ran, only on whether
-- the five ids above still exist in property_listings with the expected
-- import provenance. A count other than 5 means the id list or the
-- provenance filter itself is wrong -- abort rather than proceed on a
-- mis-scoped match.
DO $$
DECLARE
  matched_count integer;
BEGIN
  SELECT count(*) INTO matched_count
  FROM property_listings pl
  JOIN fix_2575_targets t ON t.listing_id = pl.id
  WHERE pl.parsed_data->>'importIssue' = '2304'
    AND pl.parsed_data->>'source' = '99acres';

  IF matched_count <> 5 THEN
    RAISE EXCEPTION 'fix-office-subtype-2575: expected 5 rows matching id list + provenance, found %. Aborting.', matched_count;
  END IF;
END $$;

-- Gate 3 (state) count assertion. This one IS run-dependent by design: it
-- must be exactly 0 (already corrected on a prior run -- idempotent no-op)
-- or exactly 5 (fresh, uncorrected). Any other count (1-4) means a partial
-- or corrupted prior run and must abort loudly rather than silently
-- "finish" an inconsistent correction.
DO $$
DECLARE
  old_state_count integer;
BEGIN
  SELECT count(*) INTO old_state_count
  FROM property_listings pl
  JOIN fix_2575_targets t ON t.listing_id = pl.id
  WHERE pl.parsed_data->>'importIssue' = '2304'
    AND pl.parsed_data->>'source' = '99acres'
    AND pl.property_type = 'commercial_building'
    AND pl.commercial_subtype = 'BUILDING';

  IF old_state_count NOT IN (0, 5) THEN
    RAISE EXCEPTION 'fix-office-subtype-2575: expected 0 (already corrected) or 5 (uncorrected) rows in old state, found %. Aborting -- partial/corrupt state.', old_state_count;
  END IF;
END $$;

-- Gate 4 (lcbd presence) count assertion. The rollback script re-inserts an
-- lcbd row for every target from this script's captured audit payload, but
-- unlike lcsd (which carries an explicit lcsdPreExisted flag), lcbd presence
-- is not recorded -- it is assumed. listing_commercial_building_details.
-- created_at is NOT NULL DEFAULT now(), so if a target had no lcbd row, the
-- captured lcbd_created_at would be JSON null and the rollback's re-insert
-- would raise 23502 (not-null violation) and abort. Rather than adding a
-- presence flag on trust, this gate checks the assumption at execution time:
-- it must fail loudly here, before capture, if any in-scope target lacks an
-- lcbd row. Scoped identically to Gate 3's old-state predicate so it is
-- vacuously satisfied (0 = 0) on an idempotent re-run, when no rows are
-- in-scope any more.
DO $$
DECLARE
  target_count integer;
  lcbd_count integer;
BEGIN
  SELECT count(*) INTO target_count
  FROM property_listings pl
  JOIN fix_2575_targets t ON t.listing_id = pl.id
  WHERE pl.parsed_data->>'importIssue' = '2304'
    AND pl.parsed_data->>'source' = '99acres'
    AND pl.property_type = 'commercial_building'
    AND pl.commercial_subtype = 'BUILDING';

  SELECT count(*) INTO lcbd_count
  FROM property_listings pl
  JOIN fix_2575_targets t ON t.listing_id = pl.id
  JOIN listing_commercial_building_details lcbd ON lcbd.listing_id = pl.id
  WHERE pl.parsed_data->>'importIssue' = '2304'
    AND pl.parsed_data->>'source' = '99acres'
    AND pl.property_type = 'commercial_building'
    AND pl.commercial_subtype = 'BUILDING';

  IF lcbd_count <> target_count THEN
    RAISE EXCEPTION 'fix-office-subtype-2575: expected % in-scope targets to each have an lcbd row, found %. Aborting -- rollback cannot safely capture a missing lcbd pre-image.', target_count, lcbd_count;
  END IF;
END $$;

-- Step 1: capture pre-image and write rollback-audit data into parsed_data.
-- Scoped by the full gate (ids + provenance + old state), so on a second run
-- this WHERE clause matches zero rows and nothing is overwritten.
--
-- The rollback script runs later, as a separate transaction/script, and has
-- no other way to know whether an lcsd row pre-existed for a listing before
-- this correction, what all eight of that pre-existing lcsd row's columns
-- held (this script's own UPSERT, below, overwrites all eight), or what the
-- pre-existing lcbd row's values were (this script's own DELETE, below,
-- destroys the lcbd row including its created_at). All of this is captured
-- here so the rollback script can restore the exact pre-image rather than
-- reconstructing an approximation of it.
WITH pre_image AS (
  SELECT
    pl.id AS listing_id,
    lcsd.listing_id IS NOT NULL AS lcsd_pre_existed,
    lcsd.commercial_subtype AS lcsd_prior_subtype,
    lcsd.floor_number AS lcsd_prior_floor_number,
    lcsd.total_floors AS lcsd_prior_total_floors,
    lcsd.furnishing_status AS lcsd_prior_furnishing_status,
    lcsd.washrooms AS lcsd_prior_washrooms,
    lcsd.parking_count AS lcsd_prior_parking_count,
    lcsd.road_frontage_ft AS lcsd_prior_road_frontage_ft,
    lcsd.commercial_usage AS lcsd_prior_commercial_usage,
    lcbd.number_of_units AS lcbd_number_of_units,
    lcbd.total_floors AS lcbd_total_floors,
    lcbd.road_frontage_ft AS lcbd_road_frontage_ft,
    lcbd.commercial_usage AS lcbd_commercial_usage,
    lcbd.created_at AS lcbd_created_at
  FROM property_listings pl
  JOIN fix_2575_targets t ON t.listing_id = pl.id
  LEFT JOIN listing_commercial_space_details lcsd ON lcsd.listing_id = pl.id
  LEFT JOIN listing_commercial_building_details lcbd ON lcbd.listing_id = pl.id
  WHERE pl.parsed_data->>'importIssue' = '2304'
    AND pl.parsed_data->>'source' = '99acres'
    AND pl.property_type = 'commercial_building'
    AND pl.commercial_subtype = 'BUILDING'
),
captured AS (
  UPDATE property_listings pl
  SET parsed_data = pl.parsed_data || jsonb_build_object(
    'fix2575RollbackAudit', jsonb_build_object(
      'lcsdPreExisted', pre_image.lcsd_pre_existed,
      'lcsdPriorSubtype', pre_image.lcsd_prior_subtype,
      'lcsdPriorFloorNumber', pre_image.lcsd_prior_floor_number,
      'lcsdPriorTotalFloors', pre_image.lcsd_prior_total_floors,
      'lcsdPriorFurnishingStatus', pre_image.lcsd_prior_furnishing_status,
      'lcsdPriorWashrooms', pre_image.lcsd_prior_washrooms,
      'lcsdPriorParkingCount', pre_image.lcsd_prior_parking_count,
      'lcsdPriorRoadFrontageFt', pre_image.lcsd_prior_road_frontage_ft,
      'lcsdPriorCommercialUsage', pre_image.lcsd_prior_commercial_usage,
      'lcbdNumberOfUnits', pre_image.lcbd_number_of_units,
      'lcbdTotalFloors', pre_image.lcbd_total_floors,
      'lcbdRoadFrontageFt', pre_image.lcbd_road_frontage_ft,
      'lcbdCommercialUsage', pre_image.lcbd_commercial_usage,
      'lcbdCreatedAt', pre_image.lcbd_created_at
    )
  )
  FROM pre_image
  WHERE pl.id = pre_image.listing_id
  RETURNING pl.id
)
-- Records exactly the ids this run's pre_image predicate matched (empty on
-- an idempotent re-run), so step 4 can be scoped to the same gate without
-- re-testing a state step 3 has already overwritten.
INSERT INTO fix_2575_captured (listing_id)
SELECT id FROM captured;

-- Step 2: UPSERT (never INSERT ... ON CONFLICT DO NOTHING) the lcsd row.
-- ListingCrudService.refreshTypedProjections routes on listing_family, not
-- property_type, so a Commercial-family row edited through the app since
-- import may already carry a stale lcsd row (e.g. holding 'BUILDING' or some
-- other subtype). DO NOTHING would leave that stale value in place while the
-- flat column below moves to OFFICE -- and the V135 deferred guard would
-- then abort this entire correction at COMMIT, because the row would carry
-- a disagreeing lcsd projection. Non-subtype columns are sourced from the
-- live property_listings flat columns, mirroring what the app's own writer
-- would produce -- not hardcoded.
--
-- Note: "stale" here means this row's payload diverges from what a fresh
-- OFFICE row would hold -- which is exactly, and only, the case in which
-- this UPSERT's overwrite would silently discard real data if the pre-image
-- were not already captured in full (all eight columns) by Step 1 above.
-- The motivating scenario for choosing UPSERT is also its own failure
-- scenario absent that capture; that is a property of this design worth
-- keeping visible here, not something to reason through once and discard.
INSERT INTO listing_commercial_space_details (
  listing_id, commercial_subtype, floor_number, total_floors,
  furnishing_status, washrooms, parking_count, road_frontage_ft,
  commercial_usage, created_at
)
SELECT
  pl.id,
  'OFFICE',
  pl.floor_number,
  pl.total_floors,
  pl.furnishing_status,
  pl.washrooms,
  pl.parking_count,
  pl.road_frontage_ft,
  pl.commercial_usage,
  now()
FROM property_listings pl
JOIN fix_2575_targets t ON t.listing_id = pl.id
WHERE pl.parsed_data->>'importIssue' = '2304'
  AND pl.parsed_data->>'source' = '99acres'
  AND pl.property_type = 'commercial_building'
  AND pl.commercial_subtype = 'BUILDING'
ON CONFLICT (listing_id) DO UPDATE
SET commercial_subtype = EXCLUDED.commercial_subtype,
    floor_number = EXCLUDED.floor_number,
    total_floors = EXCLUDED.total_floors,
    furnishing_status = EXCLUDED.furnishing_status,
    washrooms = EXCLUDED.washrooms,
    parking_count = EXCLUDED.parking_count,
    road_frontage_ft = EXCLUDED.road_frontage_ft,
    commercial_usage = EXCLUDED.commercial_usage;

-- Step 3: move the flat columns. Scoped by the full gate, so on a second
-- run this WHERE clause matches zero rows (property_type is already
-- 'commercial', not 'commercial_building') and is a no-op.
UPDATE property_listings pl
SET property_type = 'commercial',
    commercial_subtype = 'OFFICE'
FROM fix_2575_targets t
WHERE pl.id = t.listing_id
  AND pl.parsed_data->>'importIssue' = '2304'
  AND pl.parsed_data->>'source' = '99acres'
  AND pl.property_type = 'commercial_building'
  AND pl.commercial_subtype = 'BUILDING';

-- Step 4: remove the now-stale lcbd row. Scoped to fix_2575_captured -- the
-- ids step 1 actually matched under the full gate (ids + provenance + old
-- state) -- not to fix_2575_targets. Joining the old-state gate directly
-- here would not work: step 3 above has already moved property_type off
-- 'commercial_building', so re-testing that predicate at this point would
-- always match zero rows, even on a fresh run. Going through the captured
-- set instead keeps this DELETE in lockstep with the same gate step 1
-- applied, without re-evaluating a state step 3 has already overwritten. On
-- an idempotent re-run fix_2575_captured is empty, so this is a true no-op,
-- not merely a DELETE that happens to match nothing because the rows are
-- already gone.
DELETE FROM listing_commercial_building_details lcbd
USING fix_2575_captured c
WHERE lcbd.listing_id = c.listing_id;

-- Step 5: post-condition assertion. After this script (on a fresh run or a
-- no-op re-run), all five target listings must be
-- property_type='commercial'/commercial_subtype='OFFICE', each must have
-- exactly one lcsd row with commercial_subtype='OFFICE', and none may still
-- have an lcbd row.
DO $$
DECLARE
  bad_flat_count integer;
  missing_lcsd_count integer;
  stray_lcbd_count integer;
BEGIN
  SELECT count(*) INTO bad_flat_count
  FROM property_listings pl
  JOIN fix_2575_targets t ON t.listing_id = pl.id
  WHERE NOT (pl.property_type = 'commercial' AND pl.commercial_subtype = 'OFFICE');

  SELECT count(*) INTO missing_lcsd_count
  FROM fix_2575_targets t
  LEFT JOIN listing_commercial_space_details lcsd ON lcsd.listing_id = t.listing_id
  WHERE lcsd.listing_id IS NULL OR lcsd.commercial_subtype IS DISTINCT FROM 'OFFICE';

  SELECT count(*) INTO stray_lcbd_count
  FROM fix_2575_targets t
  JOIN listing_commercial_building_details lcbd ON lcbd.listing_id = t.listing_id;

  IF bad_flat_count <> 0 OR missing_lcsd_count <> 0 OR stray_lcbd_count <> 0 THEN
    RAISE EXCEPTION 'fix-office-subtype-2575: post-condition failed (bad_flat=%, missing_lcsd=%, stray_lcbd=%). Aborting.',
      bad_flat_count, missing_lcsd_count, stray_lcbd_count;
  END IF;
END $$;

COMMIT;
