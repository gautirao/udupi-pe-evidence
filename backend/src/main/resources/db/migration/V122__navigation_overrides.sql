-- V122: revision-scoped controlled-overrides table for the navigation hierarchy (#1955 Areas PR A,
-- SLICE 2f+2g).
--
-- Model A (architect-approved): a DEDICATED sandbox table. Overrides are REPLAYED DETERMINISTIC
-- generation INPUTS, never post-hoc tree mutations against a frozen snapshot — a regeneration
-- reloads canonical geography + policy + this table's rows and re-runs the SAME deterministic
-- pipeline (NavigationTreeGenerator, then NavigationTreeOverrideApplier's post-bisection pass),
-- then the FULL 13-invariant validation, before anything is persisted. NO production mirror, NO
-- ALTER of navigation_nodes/sandbox_navigation_nodes.
--
-- ── sandbox_navigation_override ──────────────────────────────────────────────────────────────
-- Exactly one of subject_area_key / subject_node_key is set (the XOR check below), matching
-- whichever identity the override kind operates on:
--   EXCLUDE_AREA           subject_area_key only
--   REASSIGN_AREA_REGION   subject_area_key + target_region_key
--   MOVE_AREA               subject_area_key + target_node_key (destination CLUSTER)
--   RELABEL                subject_node_key + new_label
--   SET_REPRESENTATIVES    subject_node_key + new_representative_area_keys
--
-- subject_area_key / subject_node_key are NOT foreign keys — same "sandbox rows may reference
-- geography not yet promoted" convention as sandbox_navigation_nodes.area_key (V121).

CREATE TABLE IF NOT EXISTS public.sandbox_navigation_override (
    id                              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revision_id                     BIGINT NOT NULL REFERENCES public.city_launch_revision (id) ON DELETE CASCADE,
    override_kind                   TEXT NOT NULL CHECK (override_kind IN (
                                        'EXCLUDE_AREA', 'REASSIGN_AREA_REGION', 'MOVE_AREA',
                                        'RELABEL', 'SET_REPRESENTATIVES')),
    subject_area_key                TEXT NULL,
    subject_node_key                TEXT NULL,
    target_region_key               TEXT NULL,
    target_node_key                 TEXT NULL,
    new_label                       TEXT NULL,
    new_representative_area_keys    TEXT[] NULL,
    apply_order                     INTEGER NOT NULL,
    reason                          TEXT NULL,
    created_by                      UUID NOT NULL,
    created_at                      TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT chk_sandbox_navigation_override_subject_xor
        CHECK ((subject_area_key IS NOT NULL) <> (subject_node_key IS NOT NULL)),

    CONSTRAINT chk_sandbox_navigation_override_kind_shape
        CHECK (
            CASE override_kind
                WHEN 'EXCLUDE_AREA' THEN
                    subject_area_key IS NOT NULL AND target_region_key IS NULL AND target_node_key IS NULL
                    AND new_label IS NULL AND new_representative_area_keys IS NULL
                WHEN 'REASSIGN_AREA_REGION' THEN
                    subject_area_key IS NOT NULL AND target_region_key IS NOT NULL AND target_node_key IS NULL
                    AND new_label IS NULL AND new_representative_area_keys IS NULL
                WHEN 'MOVE_AREA' THEN
                    subject_area_key IS NOT NULL AND target_node_key IS NOT NULL AND target_region_key IS NULL
                    AND new_label IS NULL AND new_representative_area_keys IS NULL
                WHEN 'RELABEL' THEN
                    subject_node_key IS NOT NULL AND new_label IS NOT NULL AND target_region_key IS NULL
                    AND target_node_key IS NULL AND new_representative_area_keys IS NULL
                WHEN 'SET_REPRESENTATIVES' THEN
                    subject_node_key IS NOT NULL AND new_representative_area_keys IS NOT NULL
                    AND target_region_key IS NULL AND target_node_key IS NULL AND new_label IS NULL
                ELSE FALSE
            END
        )
);

-- Area-keyed kinds: at most one override of a given kind per area, per revision. Two area-keyed
-- kinds (EXCLUDE_AREA/REASSIGN_AREA_REGION/MOVE_AREA) targeting the SAME area are still each
-- individually unique per-kind here — the exclude-vs-move/reassign CONFLICT itself is a service-
-- layer (NavigationTreeValidationService) check, a superset of this DB subset, matching the V121
-- precedent of "service is a strict superset of the DB constraints".
CREATE UNIQUE INDEX IF NOT EXISTS uq_sandbox_navigation_override_area_kind
    ON public.sandbox_navigation_override (revision_id, subject_area_key, override_kind)
    WHERE subject_area_key IS NOT NULL;

-- Node-keyed kinds: at most one RELABEL / one SET_REPRESENTATIVES per node, per revision.
CREATE UNIQUE INDEX IF NOT EXISTS uq_sandbox_navigation_override_node_kind
    ON public.sandbox_navigation_override (revision_id, subject_node_key, override_kind)
    WHERE subject_node_key IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_sandbox_navigation_override_revision_apply_order
    ON public.sandbox_navigation_override (revision_id, apply_order);

COMMENT ON TABLE public.sandbox_navigation_override IS
    'Revision-scoped controlled-override inputs for navigation-tree (re)generation (#1955 Areas PR '
    'A, SLICE 2f+2g). Overrides are REPLAYED DETERMINISTIC GENERATION INPUTS, never post-hoc tree '
    'mutations — a regeneration reloads canonical geography + policy + this table and re-runs the '
    'full deterministic pipeline, then the full 13-invariant validation, before anything is '
    'persisted. No production mirror table exists; overrides never survive promotion as their own '
    'row set — only their effect on the promoted navigation_nodes tree does.';
COMMENT ON COLUMN public.sandbox_navigation_override.apply_order IS
    'Tie-breaker ONLY within an override kind''s own fixed canonical processing order (see '
    'NavigationTreeOverrideApplier) — it does NOT let one kind run before another kind.';
