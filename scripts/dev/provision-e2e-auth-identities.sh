#!/usr/bin/env bash
# scripts/dev/provision-e2e-auth-identities.sh — #2236 Part B (B1-B3)
#
# Creates/updates the 4 fixed E2E identities (admin/broker/user/dealer) in a
# DEDICATED E2E Supabase project via the Admin API, then writes
# .env.e2e.auth (repo root, gitignored, mode 600) with everything EXCEPT the
# service-role key.
#
# THE SECRET-HANDLING CONTRACT (read this before running):
#   E2E_SUPABASE_SERVICE_ROLE_KEY is supplied ONLY as an ephemeral env var
#   for a single invocation of this script. It is NEVER written to
#   .env.e2e.auth, never logged, never echoed, and never passed to browser
#   code. This script is the ONLY place in the repo that ever reads it.
#
#     E2E_SUPABASE_SERVICE_ROLE_KEY=<value> \
#     E2E_SUPABASE_PROJECT_REF=<ref> \
#     E2E_SUPABASE_URL=https://<ref>.supabase.co \
#     E2E_SUPABASE_ANON_KEY=<publishable key> \
#       ./scripts/dev/provision-e2e-auth-identities.sh
#
# Idempotent / safely re-runnable: an identity that already exists gets its
# password (and role metadata) updated rather than the script failing.
#
# See docs/e2e-auth-provisioning.md for the full contract, why Option 2 was
# chosen over Option 1/3, and the Part A owner checklist this depends on.

set -euo pipefail

# --- Defend against xtrace leaking the service-role key into a transcript,
# whether inherited from a caller's `set -x`, SHELLOPTS, or BASH_XTRACEFD.
set +o xtrace
# NOTE: SHELLOPTS is readonly in bash, so `unset SHELLOPTS` always fails and
# is a best-effort no-op (kept only so a reader doesn't wonder why it's
# missing) — it is NOT an active defense. The real protections are
# `set +o xtrace` above and the DEBUG trap below (defense-in-depth); this
# BASH_XTRACEFD unset below is NOT readonly and does actively help.
unset BASH_XTRACEFD 2>/dev/null || true
trap 'set +o xtrace 2>/dev/null || true' DEBUG

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"

# shellcheck source=lib/e2e-auth-common.sh
source "${SCRIPT_DIR}/lib/e2e-auth-common.sh"

ENV_AUTH_FILE="${REPO_ROOT}/.env.e2e.auth"

DRY_RUN="false"
if [[ "${E2E_AUTH_DRY_RUN:-}" == "1" ]]; then
  DRY_RUN="true"
fi

print_help() {
  cat <<'EOF'
Usage: E2E_SUPABASE_SERVICE_ROLE_KEY=<key> scripts/dev/provision-e2e-auth-identities.sh [--dry-run]

Creates/updates the 4 fixed E2E identities (admin/broker/user/dealer) in the
E2E Supabase project (E2E_SUPABASE_PROJECT_REF / E2E_SUPABASE_URL /
E2E_SUPABASE_ANON_KEY) via the Admin API, then writes .env.e2e.auth at the
repo root (mode 600, gitignored) with everything EXCEPT the service-role key.

Required environment variables:
  E2E_SUPABASE_SERVICE_ROLE_KEY   Ephemeral only — read for this invocation,
                                   NEVER written to disk, logged, or echoed.
  E2E_SUPABASE_PROJECT_REF        E2E project ref (must differ from production).
  E2E_SUPABASE_URL                https://<ref>.supabase.co
  E2E_SUPABASE_ANON_KEY           E2E project's publishable/anon key.

Options:
  --dry-run   Run every validation/guard/coherence-check and password
              generation, print the plan, make ZERO HTTP calls, and do NOT
              write .env.e2e.auth. Exit 0 on success. Equivalent to setting
              E2E_AUTH_DRY_RUN=1.
  --help      Show this message.

Identities provisioned (role vocabulary fixed by public.app_role):
  E2E_ADMIN_EMAIL/PASSWORD    e2e-admin@udupi-e2e.invalid   role: admin
  E2E_BROKER_EMAIL/PASSWORD   e2e-broker@udupi-e2e.invalid  role: broker
  E2E_USER_EMAIL/PASSWORD     e2e-user@udupi-e2e.invalid    role: user
  E2E_DEALER_EMAIL/PASSWORD   e2e-dealer@udupi-e2e.invalid  role: dealer

Passwords are generated by this script (crypto-random, >=32 chars) — they
are never caller-supplied.
EOF
}

for arg in "$@"; do
  case "$arg" in
    --dry-run) DRY_RUN="true" ;;
    --help|-h) print_help; exit 0 ;;
    *)
      echo "ERROR: unknown argument: $arg (see --help)" >&2
      exit 1
      ;;
  esac
done

echo ">>> provision-e2e-auth-identities.sh starting (dry-run=${DRY_RUN})"

# ---------------------------------------------------------------------------
# Guard 1 — production-collision guard (runs FIRST, fail-closed)
# ---------------------------------------------------------------------------

PROD_REF_SOURCE="$(_e2e_auth_detect_production_ref "$REPO_ROOT")"
if ! _e2e_auth_collision_guard "${E2E_SUPABASE_PROJECT_REF:-}" "$PROD_REF_SOURCE"; then
  exit 1
fi
echo ">>> Production-collision guard passed (E2E ref differs from production ref)."

# ---------------------------------------------------------------------------
# Guard 2 — required project values present
# ---------------------------------------------------------------------------

if [[ -z "${E2E_SUPABASE_URL:-}" ]]; then
  echo "ERROR: E2E_SUPABASE_URL is unset/empty." >&2
  exit 1
fi
if [[ -z "${E2E_SUPABASE_ANON_KEY:-}" ]]; then
  echo "ERROR: E2E_SUPABASE_ANON_KEY is unset/empty." >&2
  exit 1
fi

# ---------------------------------------------------------------------------
# Guard 3 — issuer/browser coherence: ref extracted from E2E_SUPABASE_URL
# must equal E2E_SUPABASE_PROJECT_REF.
# ---------------------------------------------------------------------------

if ! _e2e_auth_coherence_assert "$E2E_SUPABASE_URL" "$E2E_SUPABASE_PROJECT_REF" "E2E_SUPABASE_URL vs E2E_SUPABASE_PROJECT_REF"; then
  exit 1
fi
echo ">>> URL/ref coherence check passed."

# ---------------------------------------------------------------------------
# Guard 4 — service-role key present (never printed, never logged)
# ---------------------------------------------------------------------------

if [[ -z "${E2E_SUPABASE_SERVICE_ROLE_KEY:-}" ]]; then
  echo "ERROR: E2E_SUPABASE_SERVICE_ROLE_KEY is unset/empty. Supply it as an ephemeral env var for this invocation only — it is never read from any file by this script." >&2
  exit 1
fi
echo ">>> Service-role key present ($(_e2e_auth_mask "$E2E_SUPABASE_SERVICE_ROLE_KEY"))."

# ---------------------------------------------------------------------------
# Password generation — the script generates these; never caller-supplied.
# Portable crypto-random source (macOS + Linux): openssl rand -> filter to
# alnum -> truncate to 40 chars. Assert >=32 chars, distinct per identity.
# ---------------------------------------------------------------------------

_generate_password() {
  local pw
  pw="$(LC_ALL=C openssl rand -base64 48 | LC_ALL=C tr -dc 'A-Za-z0-9' | cut -c1-40)"
  if [[ ${#pw} -lt 32 ]]; then
    echo "ERROR: password generation yielded a string shorter than 32 characters (got ${#pw}) — aborting rather than provisioning a weak credential." >&2
    return 1
  fi
  printf '%s' "$pw"
}

echo ">>> Generating per-identity passwords..."
E2E_ADMIN_PASSWORD_GEN="$(_generate_password)"
E2E_BROKER_PASSWORD_GEN="$(_generate_password)"
E2E_USER_PASSWORD_GEN="$(_generate_password)"
E2E_DEALER_PASSWORD_GEN="$(_generate_password)"
echo ">>> Passwords generated (4 distinct, >=32 chars each; not printed)."

E2E_ADMIN_EMAIL_FIXED="e2e-admin@udupi-e2e.invalid"
E2E_BROKER_EMAIL_FIXED="e2e-broker@udupi-e2e.invalid"
E2E_USER_EMAIL_FIXED="e2e-user@udupi-e2e.invalid"
E2E_DEALER_EMAIL_FIXED="e2e-dealer@udupi-e2e.invalid"

if [[ "$DRY_RUN" == "true" ]]; then
  cat <<EOF
>>> DRY RUN — no HTTP calls made, .env.e2e.auth NOT written. Plan:
    Project ref:  ${E2E_SUPABASE_PROJECT_REF}
    Project URL:  ${E2E_SUPABASE_URL}
    Identities to create/update (email_confirm=true, idempotent upsert):
      admin  -> ${E2E_ADMIN_EMAIL_FIXED}  (role: admin)
      broker -> ${E2E_BROKER_EMAIL_FIXED} (role: broker)
      user   -> ${E2E_USER_EMAIL_FIXED}   (role: user)
      dealer -> ${E2E_DEALER_EMAIL_FIXED} (role: dealer)
    Would write: ${ENV_AUTH_FILE} (mode 600) with project + identity
    email/password pairs. E2E_SUPABASE_SERVICE_ROLE_KEY is NEVER written.
>>> DRY RUN OK.
EOF
  exit 0
fi

# ---------------------------------------------------------------------------
# _admin_api_call — the ONE place this script touches HTTP. Feeds the
# service-role key via `curl --config -` on stdin (never argv, never a temp
# file) and routes through the PATH-resolved wrapper so a test harness's
# mock curl can intercept every call.
# ---------------------------------------------------------------------------

_admin_api_call() {
  local method="$1" path="$2" body="${3:-}"
  local url="${E2E_SUPABASE_URL%/}${path}"
  local cfg
  local escaped_key escaped_url
  escaped_key="$(_e2e_auth_curl_config_escape "$E2E_SUPABASE_SERVICE_ROLE_KEY")"
  escaped_url="$(_e2e_auth_curl_config_escape "$url")"
  cfg="header = \"Authorization: Bearer ${escaped_key}\"
header = \"apikey: ${escaped_key}\"
header = \"Content-Type: application/json\"
request = \"${method}\"
url = \"${escaped_url}\"
silent
show-error
write-out = \"\\n%{http_code}\""
  if [[ -n "$body" ]]; then
    cfg="${cfg}
data = \"$(_e2e_auth_curl_config_escape "$body")\""
  fi
  printf '%s\n' "$cfg" | _e2e_auth_curl_wrapper --config -
}

# _split_status <raw-response> — echoes body then status via stdout, as two
# lines (body may itself be multi-line JSON, so callers use head/tail, not
# a naive split).
_response_status() {
  printf '%s' "$1" | tail -n1
}
_response_body() {
  printf '%s' "$1" | sed '$d'
}

_lookup_user_id_by_email() {
  # #2691: GoTrue's admin list-users endpoint does NOT support an `email`
  # query filter — the param is silently ignored, so a naive `?email=...`
  # call returns an unfiltered page and reading `.[0].id` picks an ARBITRARY
  # account rather than the intended one (same defect #2307 fixed elsewhere,
  # via a by-id lookup — not available here since discovering the id from a
  # known, fixed email is the whole point of this function). The fix:
  # paginate through the full user list and filter for an EXACT email match
  # client-side, never trusting response ordering/position.
  local email="$1"
  local page=1
  local per_page=200
  local max_pages=50
  local resp status body id count

  while (( page <= max_pages )); do
    resp="$(_admin_api_call GET "/auth/v1/admin/users?page=${page}&per_page=${per_page}")"
    status="$(_response_status "$resp")"
    body="$(_response_body "$resp")"
    if [[ "$status" != 2* ]]; then
      echo "ERROR: lookup for ${email} failed (HTTP ${status}, page ${page})." >&2
      return 1
    fi

    id="$(printf '%s' "$body" | jq -r --arg email "$email" \
      '(.users // []) | map(select(.email == $email)) | .[0].id // empty' 2>/dev/null || true)"
    if [[ -n "$id" ]]; then
      printf '%s' "$id"
      return 0
    fi

    count="$(printf '%s' "$body" | jq -r '(.users // []) | length' 2>/dev/null || echo 0)"
    if [[ -z "$count" || "$count" -lt "$per_page" ]]; then
      # Short (or empty) page — end of the list, no match anywhere.
      printf ''
      return 0
    fi

    page=$((page + 1))
  done

  echo "ERROR: lookup for ${email} scanned ${max_pages} pages (per_page=${per_page}) without finding a match — aborting rather than looping unbounded." >&2
  return 1
}

_provision_identity() {
  local label="$1" email="$2" password="$3" role="$4"
  local body resp status create_body

  echo ">>> Provisioning ${label} (${email})..."

  create_body="$(jq -nc --arg email "$email" --arg password "$password" --arg role "$role" \
    '{email: $email, password: $password, email_confirm: true, app_metadata: {role: $role}, user_metadata: {role: $role}}')"

  resp="$(_admin_api_call POST "/auth/v1/admin/users" "$create_body")"
  status="$(_response_status "$resp")"
  body="$(_response_body "$resp")"

  if [[ "$status" == 2* ]]; then
    echo ">>> ${label}: created."
    return 0
  fi

  if [[ "$status" == "409" ]] || printf '%s' "$body" | grep -qi 'already.*registered'; then
    echo ">>> ${label}: already exists — updating password/role instead."
    local uid
    uid="$(_lookup_user_id_by_email "$email")"
    if [[ -z "$uid" ]]; then
      echo "ERROR: ${label} (${email}) reported as already existing but could not be looked up by email." >&2
      return 1
    fi
    local update_body update_resp update_status
    update_body="$(jq -nc --arg password "$password" --arg role "$role" \
      '{password: $password, app_metadata: {role: $role}, user_metadata: {role: $role}}')"
    update_resp="$(_admin_api_call PUT "/auth/v1/admin/users/${uid}" "$update_body")"
    update_status="$(_response_status "$update_resp")"
    if [[ "$update_status" != 2* ]]; then
      echo "ERROR: ${label} (${email}) password/role update failed (HTTP ${update_status})." >&2
      return 1
    fi
    echo ">>> ${label}: updated (id ${uid})."
    return 0
  fi

  echo "ERROR: ${label} (${email}) provisioning failed (HTTP ${status})." >&2
  return 1
}

_provision_identity "admin"  "$E2E_ADMIN_EMAIL_FIXED"  "$E2E_ADMIN_PASSWORD_GEN"  "admin"
_provision_identity "broker" "$E2E_BROKER_EMAIL_FIXED" "$E2E_BROKER_PASSWORD_GEN" "broker"
_provision_identity "user"   "$E2E_USER_EMAIL_FIXED"   "$E2E_USER_PASSWORD_GEN"   "user"
_provision_identity "dealer" "$E2E_DEALER_EMAIL_FIXED" "$E2E_DEALER_PASSWORD_GEN" "dealer"

# ---------------------------------------------------------------------------
# Write .env.e2e.auth — mode 0600 AT CREATION TIME (umask 077 + atomic
# rename), sole writer, never world-readable even momentarily, never leaves
# a partial file on failure. E2E_SUPABASE_SERVICE_ROLE_KEY is NEVER written.
# ---------------------------------------------------------------------------

echo ">>> Writing ${ENV_AUTH_FILE}..."

(
  umask 077
  TMP_FILE="$(mktemp "${REPO_ROOT}/.env.e2e.auth.XXXXXX")"
  trap 'rm -f "$TMP_FILE"' EXIT
  cat > "$TMP_FILE" <<EOF
# Generated by scripts/dev/provision-e2e-auth-identities.sh — DO NOT COMMIT.
# E2E_SUPABASE_SERVICE_ROLE_KEY is deliberately absent (ephemeral-only, never
# persisted). See docs/e2e-auth-provisioning.md.
E2E_SUPABASE_PROJECT_REF=${E2E_SUPABASE_PROJECT_REF}
E2E_SUPABASE_URL=${E2E_SUPABASE_URL}
E2E_SUPABASE_ANON_KEY=${E2E_SUPABASE_ANON_KEY}
E2E_ADMIN_EMAIL=${E2E_ADMIN_EMAIL_FIXED}
E2E_ADMIN_PASSWORD=${E2E_ADMIN_PASSWORD_GEN}
E2E_BROKER_EMAIL=${E2E_BROKER_EMAIL_FIXED}
E2E_BROKER_PASSWORD=${E2E_BROKER_PASSWORD_GEN}
E2E_USER_EMAIL=${E2E_USER_EMAIL_FIXED}
E2E_USER_PASSWORD=${E2E_USER_PASSWORD_GEN}
E2E_DEALER_EMAIL=${E2E_DEALER_EMAIL_FIXED}
E2E_DEALER_PASSWORD=${E2E_DEALER_PASSWORD_GEN}
EOF
  mv "$TMP_FILE" "${REPO_ROOT}/.env.e2e.auth"
  trap - EXIT
)

echo ">>> Wrote ${ENV_AUTH_FILE} (mode 600)."
echo ">>> Done. E2E_SUPABASE_SERVICE_ROLE_KEY was never written to disk."
